/**
 * Validates supabase/seed/questions.json and writes supabase/seed.sql.
 * Run with `npm run seed:build` (Node strips the types; no build step needed).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { QuestionBankSchema } from '../src/questions/schema.ts';

const root = new URL('../', import.meta.url);
const raw = JSON.parse(readFileSync(new URL('supabase/seed/questions.json', root), 'utf8'));
const parsed = QuestionBankSchema.safeParse(raw);
if (!parsed.success) {
  console.error(parsed.error.issues.map((i) => `${i.path.join('.')}: ${i.message}`).join('\n'));
  process.exit(1);
}
const bank = parsed.data;

const text = (value: string) => `'${value.replaceAll("'", "''")}'`;
const nullable = (value: string | undefined) => (value === undefined ? 'null' : text(value));

const lines = [
  '-- Generated by scripts/build-seed.ts from supabase/seed/questions.json. Do not edit by hand.',
  '',
  'insert into public.categories (slug, name, color, icon, sort_order, is_active) values',
  bank.categories
    .map((c) => `  (${text(c.slug)}, ${text(c.name)}, ${text(c.color)}, ${text(c.icon)}, ${c.sortOrder}, ${c.isActive})`)
    .join(',\n'),
  'on conflict (slug) do update set name = excluded.name, color = excluded.color, icon = excluded.icon,',
  '  sort_order = excluded.sort_order, is_active = excluded.is_active;',
  '',
  'insert into public.questions (category_id, prompt, options, correct_index, difficulty, explanation, image_url, is_active, is_placeholder)',
  'select c.id, q.prompt, q.options, q.correct_index, q.difficulty::public.difficulty, q.explanation, q.image_url, q.is_active, q.is_placeholder',
  'from (values',
  bank.questions
    .map(
      (q) =>
        `  (${text(q.category)}, ${text(q.prompt)}, array[${q.options.map(text).join(', ')}], ${q.correct}, ${text(q.difficulty)}, ` +
        `${nullable(q.explanation)}, ${nullable(q.image)}, ${!q.placeholder}, ${q.placeholder})`,
    )
    .join(',\n'),
  ') as q (slug, prompt, options, correct_index, difficulty, explanation, image_url, is_active, is_placeholder)',
  'join public.categories c on c.slug = q.slug;',
  '',
];

writeFileSync(new URL('supabase/seed.sql', root), lines.join('\n'));
const real = bank.questions.filter((q) => !q.placeholder).length;
console.log(`seed.sql: ${bank.categories.length} categories, ${real} questions, ${bank.questions.length - real} placeholders`);
