/** Validate the fixed six-category bank and generate an idempotent SQL seed. */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { QuestionBankSchema } from '../src/questions/schema.ts';

const root = new URL('../', import.meta.url);
const parsed = QuestionBankSchema.safeParse(JSON.parse(readFileSync(new URL('supabase/seed/questions.json', root), 'utf8')));
if (!parsed.success) {
  console.error(parsed.error.issues.map((i) => `${i.path.join('.')}: ${i.message}`).join('\n'));
  process.exit(1);
}
const bank = parsed.data;
const text = (value: string) => `'${value.replaceAll("'", "''")}'`;
const nullable = (value: string | undefined) => value === undefined ? 'null' : text(value);
const idFor = (q: (typeof bank.questions)[number]) => {
  const bytes = createHash('sha256').update(`${q.category}|${q.kind}|${q.prompt}|${q.imageSource ?? ''}`).digest();
  bytes[6] = (bytes[6]! & 15) | 64;
  bytes[8] = (bytes[8]! & 63) | 128;
  const h = bytes.toString('hex').slice(0, 32);
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
};
const lines = [
  '-- Generated by scripts/build-seed.ts from supabase/seed/questions.json.',
  'insert into public.categories (slug, name, color, icon, sort_order, is_active) values',
  bank.categories.map((c) => `(${text(c.slug)}, ${text(c.name)}, ${text(c.color)}, ${text(c.icon)}, ${c.sortOrder}, ${c.isActive})`).join(',\n'),
  'on conflict (slug) do update set name = excluded.name, color = excluded.color, icon = excluded.icon, sort_order = excluded.sort_order, is_active = excluded.is_active;',
  '',
  'insert into public.questions (id, category_id, prompt, options, correct_index, difficulty, explanation, image_url, is_active, is_placeholder, kind, image_credit, image_source)',
  'select q.id::uuid, c.id, q.prompt, q.options, q.correct_index, q.difficulty::public.difficulty, q.explanation, q.image_url, q.is_active, q.is_placeholder, q.kind, q.image_credit, q.image_source',
  'from (values',
  bank.questions.map((q) => `(${text(idFor(q))}, ${text(q.category)}, ${text(q.prompt)}, array[${q.options.map(text).join(', ')}], ${q.correct}, ${text(q.difficulty)}, ${nullable(q.explanation)}, ${nullable(q.image)}, ${!q.placeholder}, ${q.placeholder}, ${text(q.kind)}, ${nullable(q.imageCredit)}, ${nullable(q.imageSource)})`).join(',\n'),
  ') as q (id, slug, prompt, options, correct_index, difficulty, explanation, image_url, is_active, is_placeholder, kind, image_credit, image_source)',
  'join public.categories c on c.slug = q.slug',
  'on conflict (id) do update set category_id = excluded.category_id, prompt = excluded.prompt, options = excluded.options, correct_index = excluded.correct_index, difficulty = excluded.difficulty, explanation = excluded.explanation, image_url = excluded.image_url, is_active = excluded.is_active, is_placeholder = excluded.is_placeholder, kind = excluded.kind, image_credit = excluded.image_credit, image_source = excluded.image_source;',
  '',
];
writeFileSync(new URL('supabase/seed.sql', root), lines.join('\n'));
console.log(`seed.sql: ${bank.categories.length} categories, ${bank.questions.length} questions (${bank.questions.filter((q) => q.kind === 'image').length} visual)`);
